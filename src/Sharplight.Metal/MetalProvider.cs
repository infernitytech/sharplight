using Sharplight.Metal.Interop;
using Sharplight.Runtime;

namespace Sharplight.Metal;

/// <summary>
/// Native Metal execution provider for Apple GPUs on macOS: the provider-neutral kernel library (Slang) compiled to the Metal Shading
/// Language, launched through a thin Objective-C interop layer, with every buffer in shared storage on unified memory. Requires a
/// Metal 3 GPU (buffer GPU addresses) and macOS 13 or later; elsewhere it reports itself unavailable, and the Vulkan provider
/// (MoltenVK on macOS) and the CPU provider remain.
/// </summary>
/// <remarks>
/// The GPU list is process-wide (the <c>MTLDevice</c> objects are singletons of the system); provider objects are cheap and stateless.
/// </remarks>
/// <param name="options">Provider options, or <see langword="null"/> for the defaults.</param>
public sealed class MetalProvider(MetalProviderOptions? options = null) : IExecutionProvider
{
    /// <summary>The provider name (<see cref="IExecutionProvider.Name"/>).</summary>
    public const string ProviderName = "metal";

    private static readonly Lazy<(IReadOnlyList<MetalDeviceProperties> Devices, string? Error)> s_devices = new(Enumerate);
    private readonly bool _unifiedOnly = (options ?? new MetalProviderOptions()).UnifiedMemoryOnly;

    /// <inheritdoc />
    public string Name => ProviderName;

    private static (IReadOnlyList<MetalDeviceProperties> Devices, string? Error) Enumerate()
    {
        if (!OperatingSystem.IsMacOS())
        {
            return ([], "Metal is only available on macOS.");
        }

        try
        {
            System.Runtime.InteropServices.NativeLibrary.Load(MetalFramework.FoundationLibrary);
            using var pool = AutoreleasePool.Push();
            nint array = MetalFramework.CopyAllDevices();
            var devices = new List<MetalDeviceProperties>();
            if (array != 0)
            {
                ulong count = ObjCRuntime.SendUInt64(array, Selectors.Count);
                for (ulong i = 0; i < count; i++)
                {
                    nint device = ObjCRuntime.SendIndex(array, Selectors.ObjectAtIndex, (nuint)i);
                    ObjCRuntime.Send(device, Selectors.Retain);
                    devices.Add(MetalDeviceProperties.Query(device));
                }

                Foundation.Release(array);
            }

            return (devices, devices.Count == 0 ? "No Metal device." : null);
        }
        catch (Exception e) when (e is DllNotFoundException or EntryPointNotFoundException)
        {
            return ([], "Metal framework not available: " + e.Message);
        }
    }

    private IEnumerable<(MetalDeviceProperties Device, int Index)> Usable()
        => s_devices.Value.Devices.Select((d, i) => (d, i)).Where(x => x.d.MissingFeatures.Count == 0 && (!_unifiedOnly || x.d.UnifiedMemory));

    /// <inheritdoc />
    public ProviderAvailability CheckAvailability()
    {
        var (devices, error) = s_devices.Value;
        if (error is not null)
        {
            return ProviderAvailability.Unavailable(error);
        }

        int usable = Usable().Count();
        if (usable == 0)
        {
            return ProviderAvailability.Unavailable("No Metal device with the required features: " +
                string.Join("; ", devices.Select(d => $"{d.Name}: {(d.MissingFeatures.Count > 0 ? "missing " + string.Join(", ", d.MissingFeatures) : "no unified memory")}")));
        }

        return ProviderAvailability.Available($"Metal, {usable} usable device(s)");
    }

    /// <inheritdoc />
    /// <remarks>Devices lacking a required feature are not listed; <see cref="DeviceInfo.Index"/> is the position in <c>MTLCopyAllDevices</c>.</remarks>
    public IReadOnlyList<DeviceInfo> GetDevices() => [.. Usable().Select(x => x.Device.ToDeviceInfo(x.Index))];

    /// <inheritdoc />
    /// <exception cref="ArgumentException"><paramref name="device"/> was listed by another provider.</exception>
    public IComputeDevice OpenDevice(DeviceInfo device, DeviceOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(device);
        if (device.Provider != Name)
        {
            throw new ArgumentException($"Device belongs to provider '{device.Provider}'.");
        }

        return new MetalDevice(s_devices.Value.Devices[device.Index], device, options ?? new DeviceOptions());
    }

    /// <inheritdoc />
    /// <remarks>Metal Shading Language source (<c>metal</c>), generated by Slang.</remarks>
    public string? PortableCodeFormat => MetalCodeGenerator.CodeTarget;

    /// <inheritdoc />
    public bool CanCompileFor(DeviceProfile profile)
    {
        ArgumentNullException.ThrowIfNull(profile);
        return profile.Provider == Name && profile.CodeTarget == MetalCodeGenerator.CodeTarget;
    }

    /// <inheritdoc />
    /// <remarks>
    /// Runs the workload on a compile-only device of the profile, which lowers every segment and compiles its kernels to MSL exactly as an
    /// opened device with that profile would, on any operating system. The kernels of the model are the entries <c>kernel/&lt;content hash&gt;</c>.
    /// </remarks>
    public Task<PortableCodeSet> CompilePortableAsync(PortableCompilationRequest request, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Target is not { } profile)
        {
            return Task.FromResult(PortableCodeSet.Empty(Name));
        }

        if (!CanCompileFor(profile))
        {
            throw new NotSupportedException($"The Metal provider generates {MetalCodeGenerator.CodeTarget} code; cannot compile for {profile}.");
        }

        return Task.Run(() =>
        {
            using var device = new MetalProfileDevice(profile, request.DeviceOptions ?? new DeviceOptions());
            var artifacts = new CompilationArtifacts(request.Stored);
            request.Workload(device, artifacts, cancellationToken);
            return artifacts.PortableCodeFor(device);
        }, cancellationToken);
    }

    /// <inheritdoc />
    /// <remarks>No device stage yet (Metal binary archives are planned): returns an empty set.</remarks>
    public Task<DeviceCodeSet> CompileDeviceSpecificAsync(IComputeDevice device, PortableCodeSet portable, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(device);
        ArgumentNullException.ThrowIfNull(portable);
        if (device is not MetalDevice)
        {
            throw new ArgumentException($"Device {device.Info} is not an opened Metal device.", nameof(device));
        }

        return Task.FromResult(DeviceCodeSet.Empty(Name, device.Info.Name));
    }

    /// <inheritdoc />
    /// <remarks>Does nothing: the GPU list is process-wide.</remarks>
    public void Dispose()
    {
    }
}
