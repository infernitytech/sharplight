#!/usr/bin/env python3
"""Generates src/Sharplight.Core/Tensors/Grids/TrellisCodebook.cs from a ggml-common.h that defines the trellis codebook
`tq2t_lut_f16` (agentionai's llama.cpp fork, the Gyro TQ*_0 releases): 2048 two-dimensional points as f16 bit patterns.

usage: gen-trellis-codebook.py <ggml-common.h> > TrellisCodebook.cs
"""
import re
import sys


def main() -> None:
    src = open(sys.argv[1]).read()
    m = re.search(r'GGML_TABLE_BEGIN\(uint16_t, tq2t_lut_f16, 4096\)(.*?)GGML_TABLE_END', src, re.S)
    values = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', m.group(1))]
    assert len(values) == 4096, len(values)
    out = [
        'namespace Sharplight.Tensors.Grids;',
        '',
        '/// <summary>',
        '/// The codebook of the trellis-coded weight formats (<see cref="DataType.TrellisV4K8_G128"/> and its siblings): 2048 points of',
        '/// two values each, point i = (<c>Values[2i]</c>, <c>Values[2i + 1]</c>), as f16 bit patterns.',
        '/// </summary>',
        "/// <remarks>Table values copied from agentionai's llama.cpp fork, ggml/src/ggml-common.h <c>tq2t_lut_f16</c> (MIT License, Copyright (c)",
        '/// 2023-2026 The ggml authors). Generated by tools/gen-trellis-codebook.py.</remarks>',
        'internal static class TrellisCodebook',
        '{',
        '    /// <summary>The 4096 f16 bit patterns.</summary>',
        '    public static ReadOnlySpan<ushort> Values =>',
        '    [',
    ]
    for j in range(0, len(values), 16):
        out.append('        ' + ', '.join(f'0x{v:04X}' for v in values[j:j + 16]) + ',')
    out.append('    ];')
    out.append('}')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
