#!/usr/bin/env python3
"""Creates a tiny random VoxCPM2 checkpoint (the layout of OpenBMB's release, read by the voxcpm package) and its reference outputs for the speech tests.

Writes OUT (default ~/models/hf/tiny-random-voxcpm2): config.json ("architecture": "voxcpm2"; MiniCPM-4 language models of width 64 with 2 and 2 layers,
4 query / 2 key-value heads of width 16 and LongRoPE factors, local encoder and diffusion transformer of width 32 with 2 layers, 16-wide latents, an
AudioVAE V2 with the release's strides at widths 8 / 64), model.safetensors (f32, random weights), audiovae.pth ({"state_dict": ...} with the weight
normalizations unfolded, as the release ships it) and the real checkpoint's tokenizer files.

Writes FIXTURE (default tests/Sharplight.TextToSpeech.Tests/Fixtures/tiny-random-voxcpm2.json): for a zero-shot case and a cloning case (the first
2 s of AUDIO, default ~/models/audio/jfk.wav, 16 kHz) generated by tests/Sharplight.TextToSpeech.Tests/tools/make_voxcpm2_reference.py with seeded
noise: the prompt tokens, the patch count, every STRIDE-th value of the noise, of the text-semantic states, of the patches and of the audio.

Usage (in a venv with torch, the voxcpm package 2.0.3, soundfile and librosa):
    python tools/make-tiny-voxcpm2.py --tokenizer <VoxCPM2 checkpoint dir> [--out OUT] [--fixture FIXTURE] [--audio AUDIO]
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile

import numpy as np
import soundfile as sf
import torch
from safetensors.torch import save_file

STRIDE = 37
TOKENIZER_FILES = ["tokenizer.json", "tokenizer_config.json", "special_tokens_map.json"]
HERE = os.path.dirname(os.path.abspath(__file__))
REFERENCE = os.path.join(HERE, "..", "tests", "Sharplight.TextToSpeech.Tests", "tools", "make_voxcpm2_reference.py")

ap = argparse.ArgumentParser()
ap.add_argument("--tokenizer", required=True)
ap.add_argument("--out", default=os.path.expanduser("~/models/hf/tiny-random-voxcpm2"))
ap.add_argument("--fixture", default=os.path.join(HERE, "..", "tests", "Sharplight.TextToSpeech.Tests", "Fixtures", "tiny-random-voxcpm2.json"))
ap.add_argument("--audio", default=os.path.expanduser("~/models/audio/jfk.wav"))
a = ap.parse_args()

from voxcpm.model.voxcpm2 import VoxCPM2Model, VoxCPMConfig  # noqa: E402
from voxcpm.modules.audiovae import AudioVAEV2, AudioVAEConfigV2  # noqa: E402
from transformers import LlamaTokenizerFast  # noqa: E402

head_dim = 16
factors = [1.0 + 0.5 * i for i in range(head_dim // 2)]
config = {
    "architecture": "voxcpm2",
    "lm_config": {
        "bos_token_id": 1, "eos_token_id": 2, "hidden_size": 64, "intermediate_size": 128, "max_position_embeddings": 32768,
        "num_attention_heads": 4, "num_hidden_layers": 2, "num_key_value_heads": 2, "rms_norm_eps": 1e-05, "rope_theta": 10000,
        "kv_channels": head_dim,
        "rope_scaling": {"type": "longrope", "long_factor": factors, "short_factor": factors, "original_max_position_embeddings": 32768},
        "vocab_size": 73448, "use_mup": False, "scale_emb": 12, "dim_model_base": 256, "scale_depth": 1.4,
    },
    "patch_size": 4, "feat_dim": 16, "scalar_quantization_latent_dim": 16, "scalar_quantization_scale": 9,
    "residual_lm_num_layers": 2, "residual_lm_no_rope": True,
    "encoder_config": {"hidden_dim": 32, "ffn_dim": 64, "num_heads": 4, "num_layers": 2, "kv_channels": head_dim},
    "dit_config": {"hidden_dim": 32, "ffn_dim": 64, "num_heads": 4, "num_layers": 2, "kv_channels": head_dim, "mean_mode": False,
                   "cfm_config": {"sigma_min": 1e-06, "solver": "euler", "t_scheduler": "log-norm", "inference_cfg_rate": 2.0}},
    "audio_vae_config": {"encoder_dim": 8, "encoder_rates": [2, 5, 8, 8], "latent_dim": 16, "decoder_dim": 64, "decoder_rates": [8, 6, 5, 2, 2, 2],
                         "sr_bin_boundaries": [20000, 30000, 40000], "sample_rate": 16000, "out_sample_rate": 48000},
    "max_length": 512, "device": "cpu", "dtype": "float32",
}

torch.manual_seed(0)
os.makedirs(a.out, exist_ok=True)
for name in TOKENIZER_FILES:
    shutil.copy(os.path.join(a.tokenizer, name), os.path.join(a.out, name))
json.dump(config, open(os.path.join(a.out, "config.json"), "w"), indent=1)
parsed = VoxCPMConfig.model_validate(config)
vae = AudioVAEV2(config=AudioVAEConfigV2(**config["audio_vae_config"]))
model = VoxCPM2Model(parsed, LlamaTokenizerFast.from_pretrained(a.out), vae, device="cpu")
with torch.no_grad():
    # Random sample-rate conditioning and snake parameters (their initial values are ones and zeros).
    for name, p in model.named_parameters():
        if "sr_cond_model" in name or name.endswith(".alpha"):
            p.copy_(1.0 + 0.2 * torch.randn_like(p) if ("scale" in name or name.endswith(".alpha")) else 0.1 * torch.randn_like(p))
state = {k: v.contiguous() for k, v in model.state_dict().items() if not k.startswith("audio_vae.")}
save_file(state, os.path.join(a.out, "model.safetensors"))
vae_state = {k[len("audio_vae."):]: v.contiguous() for k, v in model.state_dict().items() if k.startswith("audio_vae.")}
torch.save({"state_dict": vae_state}, os.path.join(a.out, "audiovae.pth"))

work = tempfile.mkdtemp(prefix="tiny-voxcpm2-")
y, sr = sf.read(a.audio, dtype="float32")
assert sr == 16000
sf.write(os.path.join(work, "reference.wav"), y[: 2 * sr], sr, subtype="FLOAT")
cases = {"zero": [], "clone": ["--reference", os.path.join(work, "reference.wav")]}
fixture = {"stride": STRIDE, "cases": {}}
text = "Hello, tiny world."
for case, extra in cases.items():
    out = os.path.join(work, case)
    subprocess.run([sys.executable, "-I", REFERENCE, a.out, out, text, "--max-len", "6", "--seed", "7", *extra], check=True)
    info = json.load(open(os.path.join(out, "info.json")))

    def every(name):
        values = np.fromfile(os.path.join(out, name + ".bin"), dtype=np.float32)
        return [float(v) for v in values[::STRIDE]]

    fixture["cases"][case] = {
        "text": text, "reference_seconds": 2 if case == "clone" else 0, "tokens": info["tokens"], "steps": info["steps"], "samples": info["samples"],
        "noise": np.fromfile(os.path.join(out, "noise.bin"), dtype=np.float32).tolist(),
        "lm_hidden": every("lm_hidden"), "residual_hidden": every("residual_hidden"), "patches": every("patches"), "audio": every("audio"),
        "prompt_feats": every("prompt_feats"),
    }
json.dump(fixture, open(a.fixture, "w"))
shutil.rmtree(work)
print("wrote", a.out, "and", a.fixture)
