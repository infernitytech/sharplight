#!/usr/bin/env python3
"""Generates src/Sharplight.Import.Gguf/GgmlNarrowIq1Grids.cs from the ggml-common.h of unsloth's llama.cpp fork.

usage: gen-narrow-iq1-grids.py <ggml/src/ggml-common.h> > src/Sharplight.Import.Gguf/GgmlNarrowIq1Grids.cs
"""
import re
import sys

src = open(sys.argv[1]).read()


def table(name):
    m = re.search(r'GGML_TABLE_BEGIN\(uint64_t, ' + name + r', [A-Z0-9_]+\)(.*?)GGML_TABLE_END', src, re.S)
    return [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', m.group(1))]


base = table('iq1s_grid')
pos = {v: i for i, v in enumerate(base)}
out = []
out.append('namespace Sharplight.Import.Gguf;')
out.append('')
out.append('/// <summary>')
out.append("/// The codebooks of the narrow IQ1 types of unsloth's llama.cpp fork (ggml ids 64-66: IQ1_XS, IQ1_XXS, IQ1_XXXS) as indices into the")
out.append("/// 2048-entry IQ1_S grid: each fork grid is a subset of IQ1_S's, so a narrow block widens to an IQ1_S block without loss.")
out.append('/// </summary>')
out.append("/// <remarks>Derived from the fork's ggml/src/ggml-common.h tables <c>iq1_xs_grid</c>, <c>iq1_xxs_grid</c>, <c>iq1_xxxs_grid</c> and")
out.append("/// <c>iq1s_grid</c> (MIT License, Copyright (c) 2023-2026 The ggml authors): entry i is the position of the fork grid's point i in the")
out.append('/// IQ1_S grid. Generated by tools/gen-narrow-iq1-grids.py.</remarks>')
out.append('internal static class GgmlNarrowIq1Grids')
out.append('{')
names = [('iq1_xs_grid', 'Xs', 'IQ1_XS (1024 points, 10-bit index)'),
         ('iq1_xxs_grid', 'Xxs', 'IQ1_XXS (512 points, 9-bit index)'),
         ('iq1_xxxs_grid', 'Xxxs', 'IQ1_XXXS (256 points, 8-bit index)')]
for i, (n, prop, doc) in enumerate(names):
    idx = [pos[v] for v in table(n)]
    out.append(f'    /// <summary>{doc}: the IQ1_S grid index of every point.</summary>')
    out.append(f'    public static ReadOnlySpan<ushort> {prop} =>')
    out.append('    [')
    for j in range(0, len(idx), 16):
        out.append('        ' + ', '.join(str(x) for x in idx[j:j + 16]) + ',')
    out.append('    ];')
    if i < 2:
        out.append('')
out.append('}')
print('\n'.join(out))
