using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Sharplight.Cuda;

/// <summary>
/// Moves the shared arrays of a kernel from static to dynamic shared memory when they exceed the 48 KB a CUDA kernel may declare
/// statically. Slang emits every <c>groupshared</c> variable as a static <c>__shared__</c> declaration at file scope; those are
/// replaced by references into one <c>extern __shared__</c> buffer (16-byte aligned offsets), and the kernel is launched with that
/// many bytes of dynamic shared memory after opting into it (<c>CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES</c>). This lets the
/// lowering pick tiles up to the device's opt-in limit (99 KB on consumer Ampere / Ada / Blackwell, 163-227 KB on A100 / H100 /
/// B200), which Vulkan cannot (its compute shaders are limited to the 48 KB static size on NVIDIA).
/// </summary>
internal static partial class SharedMemoryRewriter
{
    /// <summary>The static shared memory a CUDA kernel may declare.</summary>
    public const int StaticLimit = 48 * 1024;

    /// <summary>Name of the dynamic shared buffer in the rewritten source.</summary>
    private const string BufferName = "sl_dynamic_shared";

    private static readonly Dictionary<string, int> s_sizes = new(StringComparer.Ordinal)
    {
        ["bool"] = 1, ["char"] = 1, ["uint8_t"] = 1, ["int8_t"] = 1, ["unsigned char"] = 1,
        ["__half"] = 2, ["half"] = 2, ["__nv_bfloat16"] = 2, ["uint16_t"] = 2, ["int16_t"] = 2, ["short"] = 2,
        ["uint"] = 4, ["int"] = 4, ["float"] = 4, ["uint32_t"] = 4, ["int32_t"] = 4, ["unsigned"] = 4, ["__half2"] = 4, ["__nv_bfloat162"] = 4,
        ["uint64_t"] = 8, ["int64_t"] = 8, ["double"] = 8, ["uint2"] = 8, ["int2"] = 8, ["float2"] = 8,
        ["uint3"] = 12, ["int3"] = 12, ["float3"] = 12,
        ["uint4"] = 16, ["int4"] = 16, ["float4"] = 16, ["ulonglong2"] = 16, ["longlong2"] = 16, ["double2"] = 16,
    };

    /// <summary>
    /// Rewrites <paramref name="source"/> to dynamic shared memory if its static shared variables exceed <see cref="StaticLimit"/>.
    /// </summary>
    /// <param name="source">CUDA C++ generated by Slang.</param>
    /// <param name="dynamicBytes">Bytes of dynamic shared memory the rewritten kernel needs at launch; 0 when the source is unchanged
    /// (it fits the static limit, or a shared variable has a type whose size is not known here).</param>
    /// <returns>The source to compile.</returns>
    public static string Rewrite(string source, out int dynamicBytes)
    {
        dynamicBytes = 0;
        var matches = DeclarationPattern().Matches(source);
        if (matches.Count == 0)
        {
            return source;
        }

        var placements = new List<(Match Match, string Type, string Name, int Offset)>();
        int total = 0;
        foreach (Match m in matches)
        {
            string type = m.Groups["type"].Value.Trim();
            int? size = SizeOf(type);
            if (size is null)
            {
                return source;
            }

            total = (total + 15) & ~15;
            placements.Add((m, type, m.Groups["name"].Value, total));
            total += size.Value;
        }

        if (total <= StaticLimit)
        {
            return source;
        }

        var sb = new StringBuilder(source.Length + 256 * placements.Count);
        int last = 0;
        bool first = true;
        foreach (var (match, type, name, offset) in placements)
        {
            sb.Append(source, last, match.Index - last);
            if (first)
            {
                sb.Append("extern __shared__ __align__(16) unsigned char ").Append(BufferName).Append("[];\n");
                first = false;
            }

            sb.Append(CultureInfo.InvariantCulture, $"#define {name} (*reinterpret_cast<{type}*>({BufferName} + {offset}))\n");
            last = match.Index + match.Length;
        }

        sb.Append(source, last, source.Length - last);
        dynamicBytes = (total + 15) & ~15;
        return sb.ToString();
    }

    /// <summary>Size in bytes of a type Slang emits for shared variables (base types, CUDA vector types, nested FixedArray).</summary>
    internal static int? SizeOf(string type)
    {
        type = type.Trim();
        var array = FixedArrayPattern().Match(type);
        if (array.Success)
        {
            int? element = SizeOf(array.Groups["element"].Value);
            return element is null ? null : element * int.Parse(array.Groups["count"].Value, CultureInfo.InvariantCulture);
        }

        return s_sizes.TryGetValue(type, out int size) ? size : null;
    }

    [GeneratedRegex(@"^(?:__device__\s+)?__shared__\s+(?<type>.+?)\s+(?<name>\w+)\s*;[ \t]*\r?$", RegexOptions.Multiline)]
    private static partial Regex DeclarationPattern();

    [GeneratedRegex(@"^FixedArray<\s*(?<element>.+)\s*,\s*(?<count>\d+)\s*>$")]
    private static partial Regex FixedArrayPattern();
}
