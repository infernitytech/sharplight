using Sharplight.Cuda.Interop;
using Sharplight.Runtime;

namespace Sharplight.Cuda;

/// <summary>
/// Native CUDA execution provider for NVIDIA GPUs: the provider-neutral kernel library (Slang) compiled to CUDA C++, then to PTX with the
/// runtime compiler NVRTC, loaded and launched through the CUDA driver API. Needs only the NVIDIA driver: NVRTC and the headers it uses
/// come with the <c>Sharplight.Cuda.Runtime</c> package, and models precompiled for a profile (PTX, plus cubins for a device) load
/// without NVRTC at all. Without the driver, or without a GPU of compute capability 7.5 or later, it reports itself unavailable.
/// </summary>
/// <remarks>The GPU list is process-wide (the driver is initialized once); provider objects are cheap and stateless.</remarks>
/// <param name="options">Provider options, or <see langword="null"/> for the defaults.</param>
public sealed class CudaProvider(CudaProviderOptions? options = null) : IExecutionProvider
{
    /// <summary>The provider name (<see cref="IExecutionProvider.Name"/>).</summary>
    public const string ProviderName = "cuda";

    private static readonly Lazy<(IReadOnlyList<CudaDeviceProperties> Devices, string? Error)> s_devices = new(Enumerate);
    private readonly bool _includeIntegrated = (options ?? new CudaProviderOptions()).IncludeIntegrated;

    /// <inheritdoc />
    public string Name => ProviderName;

    private static unsafe (IReadOnlyList<CudaDeviceProperties> Devices, string? Error) Enumerate()
    {
        CudaLibraries.EnsureResolver();
        try
        {
            int result = CudaApi.cuInit(0);
            if (result == (int)CuResult.NoDevice)
            {
                return ([], "No CUDA device.");
            }

            CudaApi.Check(result, "cuInit");
            int version;
            CudaApi.Check(CudaApi.cuDriverGetVersion(&version), "cuDriverGetVersion");
            int count;
            CudaApi.Check(CudaApi.cuDeviceGetCount(&count), "cuDeviceGetCount");
            var devices = new List<CudaDeviceProperties>(count);
            for (int i = 0; i < count; i++)
            {
                devices.Add(CudaDeviceProperties.Query(i, version));
            }

            return (devices, devices.Count == 0 ? "No CUDA device." : null);
        }
        catch (Exception e) when (e is DllNotFoundException or EntryPointNotFoundException)
        {
            return ([], "NVIDIA driver (CUDA driver API) not found: " + e.Message);
        }
        catch (CudaException e)
        {
            return ([], e.Message);
        }
    }

    private IEnumerable<(CudaDeviceProperties Device, int Index)> Usable()
        => s_devices.Value.Devices.Select((d, i) => (d, i)).Where(x => x.d.Unsupported is null && (_includeIntegrated || !x.d.Integrated));

    /// <inheritdoc />
    public ProviderAvailability CheckAvailability()
    {
        var (devices, error) = s_devices.Value;
        if (error is not null)
        {
            return ProviderAvailability.Unavailable(error);
        }

        int usable = Usable().Count();
        if (usable == 0)
        {
            return ProviderAvailability.Unavailable("No supported CUDA device: " + string.Join("; ", devices.Select(d => $"{d.Name}: {d.Unsupported ?? "integrated GPUs are excluded"}")));
        }

        var nvrtc = NvrtcTranslator.NvrtcVersion;
        string compiler = nvrtc is null ? "no NVRTC (only precompiled kernels load; add Sharplight.Cuda.Runtime)" : $"NVRTC {nvrtc}";
        return ProviderAvailability.Available($"CUDA driver {devices[0].DriverText}, {usable} usable device(s), {compiler}");
    }

    /// <inheritdoc />
    /// <remarks>Devices below compute capability 7.5 are not listed; <see cref="DeviceInfo.Index"/> is the driver's device ordinal.</remarks>
    public IReadOnlyList<DeviceInfo> GetDevices() => [.. Usable().Select(x => x.Device.ToDeviceInfo(x.Index))];

    /// <inheritdoc />
    /// <exception cref="ArgumentException"><paramref name="device"/> was listed by another provider.</exception>
    public IComputeDevice OpenDevice(DeviceInfo device, DeviceOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(device);
        if (device.Provider != Name)
        {
            throw new ArgumentException($"Device belongs to provider '{device.Provider}'.");
        }

        return new CudaDevice(s_devices.Value.Devices[device.Index], device, options ?? new DeviceOptions());
    }

    /// <inheritdoc />
    /// <remarks>PTX (<c>ptx</c>) for the profile's compute capability, generated by Slang and NVRTC.</remarks>
    public string? PortableCodeFormat => CudaCodeGenerator.CodeFormat;

    /// <inheritdoc />
    public bool CanCompileFor(DeviceProfile profile)
    {
        ArgumentNullException.ThrowIfNull(profile);
        return profile.Provider == Name && CudaCodeGenerator.TryParseCodeTarget(profile.CodeTarget, out _);
    }

    /// <inheritdoc />
    /// <remarks>
    /// Runs the workload on a compile-only device of the profile, which lowers every segment and compiles its kernels to PTX exactly as an
    /// opened device with that profile would, without a GPU (NVRTC is needed). The kernels of the model are the entries
    /// <c>kernel/&lt;content hash&gt;</c>.
    /// </remarks>
    public Task<PortableCodeSet> CompilePortableAsync(PortableCompilationRequest request, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        if (request.Target is not { } profile)
        {
            return Task.FromResult(PortableCodeSet.Empty(Name));
        }

        if (!CanCompileFor(profile))
        {
            throw new NotSupportedException($"The CUDA provider generates PTX for a compute capability (code target ptx_XY); cannot compile for {profile}.");
        }

        return Task.Run(() =>
        {
            using var device = new CudaProfileDevice(profile, request.DeviceOptions ?? new DeviceOptions());
            var artifacts = new CompilationArtifacts(request.Stored);
            request.Workload(device, artifacts, cancellationToken);
            return artifacts.PortableCodeFor(device);
        }, cancellationToken);
    }

    /// <inheritdoc />
    /// <remarks>
    /// Links the PTX of every kernel into a cubin for this GPU with the driver's JIT compiler (entries <c>cubin/&lt;content hash&gt;</c>),
    /// which later loads take instead of compiling the PTX. Empty when <see cref="DeviceFeatures.KernelBinaries"/> is disabled for the device.
    /// </remarks>
    public Task<DeviceCodeSet> CompileDeviceSpecificAsync(IComputeDevice device, PortableCodeSet portable, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(device);
        ArgumentNullException.ThrowIfNull(portable);
        if (device is not CudaDevice cuda)
        {
            throw new ArgumentException($"Device {device.Info} is not an opened CUDA device.", nameof(device));
        }

        return Task.Run(() => cuda.CompileDeviceCode(portable, cancellationToken), cancellationToken);
    }

    /// <inheritdoc />
    /// <remarks>Does nothing: the GPU list is process-wide.</remarks>
    public void Dispose()
    {
    }
}
