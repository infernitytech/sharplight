#!/usr/bin/env python3
"""Generates the IQ lookup grids of Sharplight from llama.cpp's ggml/src/ggml-common.h.

usage: gen-quant-grids.py <ggml-common.h> <repository root>

Writes one C# table file per format into src/Sharplight.Core/Tensors/Grids/. The CPU dequantizers read them directly; the Vulkan
lowering packs the same tables into a device buffer (Sharplight.Shaders GridTables). The tables are copied verbatim from
ggml-common.h (MIT licence, Copyright (c) 2023-2024 The ggml authors); the generated files carry the attribution. Re-running the
script reproduces the committed files.
"""
import re
import sys
from pathlib import Path

ATTRIBUTION = ("Table values copied from llama.cpp ggml/src/ggml-common.h "
               "(MIT License, Copyright (c) 2023-2024 The ggml authors). Generated by tools/gen-quant-grids.py.")


def read_table(text: str, name: str) -> list[int]:
    match = re.search(r"GGML_TABLE_BEGIN\(\w+, " + name + r", \w+\)(.*?)GGML_TABLE_END\(\)", text, re.S)
    if match is None:
        raise SystemExit("table not found: " + name)
    return [int(token, 0) for token in re.findall(r"0x[0-9a-fA-F]+|-?\d+", match.group(1))]


def csharp_array(values: list[int], width: int, indent: str = "        ") -> str:
    digits = width * 2
    lines = []
    for start in range(0, len(values), 8):
        chunk = ", ".join(f"0x{value:0{digits}X}" for value in values[start:start + 8])
        lines.append(f"{indent}{chunk},")
    return "\n".join(lines)


def write_csharp(path: Path, type_name: str, summary: str, element: str, width: int, values: list[int]) -> None:
    body = csharp_array(values, width)
    text = f"""namespace Sharplight.Tensors.Grids;

/// <summary>{summary}</summary>
/// <remarks>{ATTRIBUTION}</remarks>
internal static class {type_name}
{{
    /// <summary>The {len(values)} table entries.</summary>
    public static ReadOnlySpan<{element}> Values =>
    [
{body}
    ];
}}
"""
    path.write_text(text)


def check_iq1_gpu_layout(cpu: list[int], gpu: list[int]) -> None:
    """The GPU table holds (value + 1) per grid value: the low nibbles of the four bytes hold values 0..3, the high nibbles 4..7."""
    for index, entry in enumerate(cpu):
        values = [((entry >> (8 * j)) & 0xFF) for j in range(8)]
        signed = [v - 256 if v > 127 else v for v in values]
        packed = 0
        for j in range(4):
            packed |= (signed[j] + 1) << (8 * j)
            packed |= (signed[j + 4] + 1) << (8 * j + 4)
        if packed != gpu[index]:
            raise SystemExit(f"iq1s_grid_gpu[{index}] does not match the documented nibble layout")


def main() -> None:
    text = Path(sys.argv[1]).read_text()
    root = Path(sys.argv[2])
    grids = root / "src/Sharplight.Core/Tensors/Grids"
    grids.mkdir(parents=True, exist_ok=True)

    write_csharp(grids / "Iq2XxsGrid.cs", "Iq2XxsGrid", "IQ2_XXS grid: 256 entries of eight unsigned bytes (little endian), ggml iq2xxs_grid.", "ulong", 8, read_table(text, "iq2xxs_grid"))
    write_csharp(grids / "Iq2XsGrid.cs", "Iq2XsGrid", "IQ2_XS grid: 512 entries of eight unsigned bytes (little endian), ggml iq2xs_grid.", "ulong", 8, read_table(text, "iq2xs_grid"))
    write_csharp(grids / "Iq2SGrid.cs", "Iq2SGrid", "IQ2_S grid: 1024 entries of eight unsigned bytes (little endian), ggml iq2s_grid.", "ulong", 8, read_table(text, "iq2s_grid"))
    write_csharp(grids / "Iq3XxsGrid.cs", "Iq3XxsGrid", "IQ3_XXS grid: 256 entries of four unsigned bytes (little endian), ggml iq3xxs_grid.", "uint", 4, read_table(text, "iq3xxs_grid"))
    write_csharp(grids / "Iq3SGrid.cs", "Iq3SGrid", "IQ3_S grid: 512 entries of four unsigned bytes (little endian), ggml iq3s_grid.", "uint", 4, read_table(text, "iq3s_grid"))
    iq1s = read_table(text, "iq1s_grid")
    write_csharp(grids / "Iq1SGrid.cs", "Iq1SGrid", "IQ1_S / IQ1_M grid: 2048 entries of eight signed bytes in {-1, 0, 1} (little endian), ggml iq1s_grid.", "ulong", 8, iq1s)
    write_csharp(grids / "IqSigns.cs", "IqSigns", "Sign patterns of the IQ2 / IQ3 formats: a 7-bit index selects the signs of eight values (bit j set = value j negative; the eighth sign is the parity of the other seven), ggml ksigns_iq2xs.", "byte", 1, read_table(text, "ksigns_iq2xs"))

    # The Vulkan kernels read the IQ1 grid in ggml's compact GPU layout, which GridTables derives from the table above; verify the layout.
    check_iq1_gpu_layout(iq1s, read_table(text, "iq1s_grid_gpu"))


if __name__ == "__main__":
    main()
